/**
 * Short landing URLs → the tool page they stand for.
 *
 * Why: Persian users share and remember short addresses (`/salary`, `/pdf`)
 * far better than `/tools/salary-tax`, and search engines get a second,
 * keyword-shaped entry point. Each short URL renders a *landing page* (value
 * proposition + FAQ + the tool inline for the main ones) and its `canonical`
 * points at itself, so there is no duplicate content with the long URL.
 */
export interface Landing {
  /** URL segment under the site root, e.g. "salary" → /salary */
  path: string;
  /** Canonical tool slug that does the actual work. */
  slug: string;
  /** H1 — keyword shaped, not the tool's internal name. */
  title: string;
  /** Meta description (150–160 chars). */
  description: string;
  /** Short intro paragraph under the H1. */
  intro: string;
  /** 3–5 bullet points: what you get. */
  bullets: string[];
  /** 3–4 FAQ pairs, also emitted as FAQPage structured data. */
  faq: { q: string; a: string }[];
  /** Related tool slugs shown at the bottom. */
  related: string[];
  /** Whether the tool itself is rendered inline on this landing page. */
  embed: boolean;
}

